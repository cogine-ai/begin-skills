const assert=require('node:assert/strict');
const M=require('../shortlist-model.js');
const C=require('../catalogue.js');
let state=M.initial();
assert.equal(M.prepare(state).ok,false,'empty selection cannot prepare');
state=M.edit(state,'ids',['arc','fold']);
state=M.edit(state,'label','North desk');
state=M.edit(state,'note','Keep the shelf edge clear.');
state=M.prepare(state).state;
assert.equal(M.isCurrent(state),true);
assert.equal(state.prepared.version,1);
const kept=M.keep(state).record;
const text=M.text(state.prepared);
assert.ok(text.includes('Workspace: North desk\nObjects selected: 2'));
assert.ok(text.includes('Width: 310 mm | Depth: 245 mm | Height: 465 mm'));
assert.ok(text.includes('Width: 285 mm | Depth: 195 mm | Height: 38 mm'));
assert.ok(text.includes('Illustrative reference price: USD 240.00'));
assert.ok(text.includes('Illustrative reference price: USD 78.00'));
assert.ok(text.includes('Workspace note: Keep the shelf edge clear.'));
state=M.edit(state,'ids',['arc']);
assert.equal(M.isCurrent(state),false,'selection edit makes preparation stale');
assert.equal(M.keep(state).ok,false,'stale keep is blocked');
assert.deepEqual(state.prepared.input.ids,['arc','fold'],'prior sheet stays intact');
state=M.prepare(state).state;
assert.equal(state.prepared.version,2);
assert.deepEqual(state.prepared.input.ids,['arc']);
const restored=M.restore(kept);
assert.equal(M.isCurrent(restored),true);
assert.deepEqual(restored.input.ids,['arc','fold']);
assert.equal(restored.input.note,'Keep the shelf edge clear.');
let changed=M.edit(restored,'note','Changed');
changed=M.edit(changed,'note','Keep the shelf edge clear.');
assert.equal(M.isCurrent(changed),false,'changing back requires preparation');
assert.equal(M.restore({...kept,catalogueRevision:'old'}),null);
assert.equal(M.restore({...kept,input:{...kept.input,ids:['arc','arc']}}),null);
assert.equal(M.restore({...kept,prepared:{...kept.prepared,signature:'altered'}}),null);
assert.equal(M.prepare(M.edit(restored,'label','')).ok,false);
assert.equal(M.prepare(M.edit(restored,'note','x'.repeat(601))).ok,false);
let all=M.edit(M.initial(),'ids',C.items.map(item=>item.id));
all=M.prepare(all).state;
assert.equal(all.prepared.input.ids.length,6);
assert.ok(M.text(all.prepared).includes('Grid 05 folded desktop utensil organizer'));
console.log('PASS: empty, six-entry, exact specimen, stale, prepare again, keep/restore and invalid-record fixtures');
